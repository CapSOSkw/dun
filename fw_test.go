// 甲骨文 Ubuntu 镜像自带的规则，nat 段那条是只在文件里、开机才加载的
const ociRules = `# Generated by iptables-save
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A POSTROUTING -s 10.99.0.0/24 -o ens3 -j MASQUERADE
COMMIT
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:InstanceServices - [0:0]
-A INPUT -m state --state RELATED,ESTABLISHED -j ACCEPT
-A INPUT -p icmp -j ACCEPT
-A INPUT -i lo -j ACCEPT
-A INPUT -p tcp -m tcp --dport 888 -j DROP
-A INPUT -p tcp -m state --state NEW -m tcp --dport 22 -j ACCEPT
-A INPUT -j REJECT --reject-with icmp-host-prohibited
-A FORWARD -j REJECT --reject-with icmp-host-prohibited
-A OUTPUT -d 169.254.0.0/16 -j InstanceServices
COMMIT
`

func TestFwInsertPos(t *testing.T) {
	for _, tc := range []struct {
		name    string
		rules   string
		managed bool
		pos     int
		need    bool
	}{
		{"甲骨文兜底 REJECT", "-P INPUT ACCEPT\n-A INPUT -m state --state RELATED,ESTABLISHED -j ACCEPT\n-A INPUT -p tcp -m tcp --dport 888 -j DROP\n-A INPUT -j REJECT --reject-with icmp-host-prohibited", false, 3, true},
		{"封 IP 不算兜底", "-P INPUT ACCEPT\n-A INPUT -s 198.51.100.7/32 -j DROP\n-A INPUT -m conntrack --ctstate INVALID -j DROP", false, 0, false},
		{"策略 DROP 加在最后", "-P INPUT DROP\n-A INPUT -i lo -j ACCEPT\n-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT", false, 0, true},
		{"ufw 管着的 DROP 策略", "-P INPUT DROP\n-A INPUT -j ufw-before-logging-input\n-A INPUT -j ufw-before-input\n-A INPUT -j ufw-reject-input", true, 0, false},
		{"ufw 和甲骨文 REJECT 叠在一起", "-P INPUT DROP\n-A INPUT -i lo -j ACCEPT\n-A INPUT -j REJECT --reject-with icmp-host-prohibited\n-A INPUT -j ufw-before-input", true, 2, true},
		{"网卡兜底和带空格注释", "-P INPUT ACCEPT\n-A INPUT -i eth0 -m comment --comment \"block all\" -j DROP", false, 1, true},
		{"什么都不拦", "-P INPUT ACCEPT", false, 0, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			pos, need := fwInsertPos(strings.Split(tc.rules, "\n"), tc.managed)
			if pos != tc.pos || need != tc.need {
				t.Fatalf("得到 %d %v，应为 %d %v", pos, need, tc.pos, tc.need)
			}
		})
	}
}

func TestFwRulesFile(t *testing.T) {
	line := "-A INPUT -p tcp -m tcp --dport 8443 -m comment --comment dun-allow -j ACCEPT"
	got, changed := fwInsertLine(ociRules, line)
	if !changed {
		t.Fatal("没插进去")
	}
	want := strings.Replace(ociRules, "-A INPUT -j REJECT", line+"\n-A INPUT -j REJECT", 1)
	if got != want {
		t.Fatalf("插入位置不对：\n%s", got)
	}
	if again, changed := fwInsertLine(got, line); changed || again != got {
		t.Fatal("同一条插了两次")
	}
	udp := "-A INPUT -p udp -m udp --dport 20000:21000 -m comment --comment dun-allow -j ACCEPT"
	got, _ = fwInsertLine(got, udp)
	back, changed := fwStripTagged(got)
	if !changed || back != ociRules {
		t.Fatalf("删掉标记行后和原文件不一致：\n%s", back)
	}

	noInput := "*filter\n:INPUT DROP [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n-A OUTPUT -o lo -j ACCEPT\nCOMMIT\n"
	got, _ = fwInsertLine(noInput, line)
	if got != strings.Replace(noInput, "COMMIT", line+"\nCOMMIT", 1) {
		t.Fatalf("没有 INPUT 规则时应放在 COMMIT 前：\n%s", got)
	}
	policy := "*filter\n:INPUT DROP [0:0]\n-A INPUT -i lo -j ACCEPT\n-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT\n-A OUTPUT -o lo -j ACCEPT\nCOMMIT\n"
	got, _ = fwInsertLine(policy, line)
	if got != strings.Replace(policy, "--dport 22 -j ACCEPT\n", "--dport 22 -j ACCEPT\n"+line+"\n", 1) {
		t.Fatalf("DROP 策略时应跟在最后一条 INPUT 后：\n%s", got)
	}
	for _, bad := range []string{"", "*nat\n:PREROUTING ACCEPT [0:0]\nCOMMIT\n", "*filter\n:INPUT ACCEPT [0:0]\n"} {
		if out, changed := fwInsertLine(bad, line); changed || out != bad {
			t.Fatalf("没有完整 *filter 段的文件不该改：%q", bad)
		}
	}
	user := "-A INPUT -p tcp -m tcp --dport 8443 -m comment --comment \"dun-allow old\" -j ACCEPT"
	if fwTagged(user) || !fwTagged(line) || fwTagged("-A OUTPUT -m comment --comment dun-allow -j ACCEPT") {
		t.Fatal("标记识别不对")
	}
}

func TestFwFields(t *testing.T) {
	f := fwFields(`-A INPUT -m comment --comment "a \"b\" c" -j DROP`)
	if len(f) != 8 || f[5] != `a "b" c` || f[7] != "DROP" {
		t.Fatalf("%q", f)
	}
}

func TestTrimLog(t *testing.T) {
	p := t.TempDir() + "/dun.log"
	var b strings.Builder
	for i := 0; b.Len() < 3000; i++ {
		b.WriteString("line " + strings.Repeat("x", i%7) + "\n")
	}
	b.WriteString("last line\n")
	os.WriteFile(p, []byte(b.String()), 0644)
	trimLog(p, 1000, 200)
	got, _ := os.ReadFile(p)
	if len(got) > 200 || !strings.HasSuffix(string(got), "last line\n") || !strings.HasPrefix(string(got), "line") {
		t.Fatalf("截断不对：%d 字节 %q", len(got), got)
	}
	small := t.TempDir() + "/small.log"
	os.WriteFile(small, []byte("a\nb\n"), 0644)
	trimLog(small, 1000, 200)
	if got, _ := os.ReadFile(small); string(got) != "a\nb\n" {
		t.Fatal("没超过上限的不该动")
	}
}
